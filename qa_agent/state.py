from __future__ import annotations

from typing import Annotated, TypedDict

from langchain_core.messages import BaseMessage

try:
    from langgraph.graph.message import add_messages  # type: ignore
except Exception:  # pragma: no cover - fallback for environments without langgraph
    def add_messages(x):  # type: ignore
        return x


class QAState(TypedDict):
    """
    LangGraph state for the QA agent.

    - ticket_id: ID of the Linear ticket being processed.
    - ticket_data: Raw response payload returned from Linear for this ticket.
    - existing_test_cases: Previously posted test cases text, if any exists.
    - user_decision: User choice about how to handle existing tests ("replace" | "supplement" | "skip").
    - notion_queries: Search terms the agent will use against Notion.
    - notion_search_results: Raw search result objects returned from Notion.
    - notion_pages: Fetched Notion page contents used as detailed context.
    - draft_test_cases: Initial test case draft generated by the agent.
    - reviewed_test_cases: Final, reviewed version of the test cases.
    - user_feedback: Free-form feedback from the user about the test cases.
    - approved: Whether the current test cases have been approved.
    - want_playwright: Whether the user wants Playwright tests generated.
    - playwright_project_path: Filesystem path to the Playwright project, if any.
    - playwright_tests: Generated Playwright test code as text.
    - published: Whether the final output has been published back to external systems.
    - messages: Conversation history as LangChain messages (managed with add_messages).
    """

    ticket_id: str
    ticket_data: dict
    existing_test_cases: str | None
    user_decision: str | None
    notion_queries: list[str]
    notion_search_results: list[dict]
    notion_pages: list[dict]
    draft_test_cases: str | None
    reviewed_test_cases: str | None
    user_feedback: str | None
    approved: bool
    want_playwright: bool | None
    playwright_project_path: str | None
    playwright_tests: str | None
    published: bool
    messages: Annotated[list[BaseMessage], add_messages]
